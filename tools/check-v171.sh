#!/bin/sh
# A3: the derived VGM 1.71 corpus file must (1) equal a fresh tools/mkvgm171.py run,
# (2) render bit-identically to its 1.50 source on the host reference, (3) be audible.
# usage: check-v171.sh   (needs build/render-ref)
set -e
SRC=corpus/vgz-sonic3dblast-title.vgz; DER=corpus/vgz-sonic3dblast-title-v171.vgz
T=${V171_TMP:-build/v171}; mkdir -p $T
python3 -I tools/mkvgm171.py $SRC $T/regen.vgz
cmp -s $T/regen.vgz $DER || { echo "FAIL v171: committed $DER differs from mkvgm171.py output"; exit 1; }
build/render-ref $SRC $T/a.raw -1 10000 44100 s16 > /dev/null 2>&1
build/render-ref $DER $T/b.raw -1 10000 44100 s16 > /dev/null 2>&1
cmp -s $T/a.raw $T/b.raw || { echo "FAIL v171: 1.71 render differs from 1.50 render"; exit 1; }
build/render-ref -i $SRC > $T/a.txt 2>&1; build/render-ref -i $DER > $T/b.txt 2>&1
cmp -s $T/a.txt $T/b.txt || { echo "FAIL v171: GetInfo (GD3/length) differs"; exit 1; }
# Loop offset shift: marko-staff loops (0x1C != 0, length 53 s); render past the loop point.
LSRC=corpus/vgz-marko-staff.vgz
python3 -I tools/mkvgm171.py $LSRC $T/loop171.vgz
build/render-ref $LSRC $T/la.raw -1 70000 22050 s16 > /dev/null 2>&1
build/render-ref $T/loop171.vgz $T/lb.raw -1 70000 22050 s16 > /dev/null 2>&1
cmp -s $T/la.raw $T/lb.raw || { echo "FAIL v171: 1.71 loop render differs from 1.50 loop render"; exit 1; }
python3 -I - $T/a.raw $T/b.raw <<'PY'
import sys, struct, math
for p in sys.argv[1:]:
    d = open(p, "rb").read()
    n = len(d) // 2
    s = struct.unpack(">%dh" % n, d[:n * 2])
    rms = math.sqrt(sum(x * x for x in s) / n) if n else 0
    print("rms %s = %.1f" % (p, rms))
    if rms <= 0:
        print("FAIL v171: silent render"); sys.exit(1)
PY
echo "ok v171: regenerated bytes match, renders identical (incl. loop), non-silent"
